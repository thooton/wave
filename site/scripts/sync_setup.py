#!/usr/bin/env python3
"""Keep the site's setup-descriptor snapshot in step with wave_packages.

    python3 site/scripts/sync_setup.py ../sonim            regenerate from its HEAD
    python3 site/scripts/sync_setup.py ../sonim --check    snapshot matches the recorded commit
    python3 site/scripts/sync_setup.py --check             offline: record and snapshot agree

The six apps' `wave-setup.json` descriptors are read from the committed
files of a wave_packages checkout (`git show <commit>:path`, so uncommitted
edits never leak in) and written to `site/setup/descriptors.mjs`. The commit
they came from is recorded in `site/setup/UPSTREAM` (same format as
`common/UPSTREAM`) and repeated in the snapshot's first line. `--check`
regenerates from the recorded commit and fails on any difference, so a
snapshot that was edited by hand, or recorded against the wrong commit, is
caught. It only notes (exit 0) that wave_packages has newer descriptor
changes; re-run without `--check` to take them, and review the diff.
No environment files, credentials or APK contents are read.
"""
import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

APPS = ('authenticator', 'canvas', 'charge', 'flashcards', 'mail', 'places')
SETUP = Path(__file__).resolve().parents[1] / 'setup'
OUTPUT = SETUP / 'descriptors.mjs'
UPSTREAM = SETUP / 'UPSTREAM'
REPOSITORY = 'https://github.com/thooton/wave_packages.git'
HEADER = '// Generated by scripts/sync_setup.py from wave_packages at '
FOOTNOTE = '; edit the app assets, not this file.\n'
SHA = re.compile(r'[0-9a-f]{40}')


def asset(app):
    return f'{app}/android/app/src/main/assets/wave-setup.json'


def git(root, *args):
    try:
        done = subprocess.run(['git', '-C', str(root), *args], capture_output=True, check=True)
    except FileNotFoundError:
        raise SystemExit('sync_setup: git is required')
    except subprocess.CalledProcessError as error:
        raise SystemExit(f'sync_setup: git {args[0]} failed in {root}: '
                         + error.stderr.decode('utf-8', 'replace').strip())
    return done.stdout


def generate(root, commit):
    descriptors = []
    for app in APPS:
        raw = git(root, 'show', f'{commit}:{asset(app)}')
        if not raw or len(raw) > 32768:
            raise SystemExit(f'sync_setup: expected a small descriptor file for {app}')
        descriptor = json.loads(raw.decode('utf-8'))
        if descriptor['app'] != app or descriptor['format'] != 1:
            raise SystemExit(f'sync_setup: descriptor id or version mismatch for {app}')
        descriptors.append(descriptor)
    return (HEADER + commit + FOOTNOTE
            + 'export const descriptors = ' + json.dumps(descriptors, indent=2, ensure_ascii=True) + ';\n')


def recorded():
    try:
        lines = UPSTREAM.read_text(encoding='utf-8').splitlines()
    except OSError:
        raise SystemExit('sync_setup: site/setup/UPSTREAM is missing; run sync_setup.py <wave_packages>')
    if len(lines) < 2 or lines[0] != REPOSITORY or not SHA.fullmatch(lines[1]):
        raise SystemExit('sync_setup: site/setup/UPSTREAM must hold the repository URL and a 40-digit commit')
    return lines[1]


def check(root):
    commit = recorded()
    snapshot = OUTPUT.read_text(encoding='utf-8') if OUTPUT.exists() else ''
    if not snapshot.startswith(HEADER + commit + FOOTNOTE):
        raise SystemExit(f'sync_setup: descriptors.mjs does not say it came from {commit}')
    if root is None:
        print(f'setup snapshot is recorded against {commit} (offline; pass wave_packages to compare)')
        return
    if git(root, 'cat-file', '-t', commit).strip() != b'commit':
        raise SystemExit(f'sync_setup: {commit} is not a commit in {root}')
    if generate(root, commit) != snapshot:
        raise SystemExit(f'sync_setup: the site descriptors differ from wave_packages at {commit}; '
                         'edit the app assets, then run sync_setup.py without --check and commit the result')
    print(f'setup snapshot matches wave_packages at {commit}')
    head = git(root, 'rev-parse', 'HEAD').decode().strip()
    paths = [asset(app) for app in APPS]
    if head != commit and subprocess.run(['git', '-C', str(root), 'diff', '--quiet', commit, head, '--', *paths]).returncode:
        print(f'sync_setup: wave_packages has newer descriptor changes at {head} (not copied)', file=sys.stderr)


def sync(root):
    commit = git(root, 'rev-parse', 'HEAD').decode().strip()
    OUTPUT.write_text(generate(root, commit), encoding='utf-8')
    UPSTREAM.write_text(f'{REPOSITORY}\n{commit}\n', encoding='utf-8')
    print(f'site/setup synced from wave_packages at {commit}')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('packages', type=Path, nargs='?')
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    root = args.packages.resolve(strict=True) if args.packages else None
    if args.check:
        check(root)
    elif root is None:
        parser.error('give the wave_packages checkout to sync from')
    else:
        sync(root)
