#!/usr/bin/env python3
"""Copy the six reviewed wave_packages app descriptors to a static ES module.

    python3 site/scripts/sync_setup.py ../sonim [--check]

No environment files, credentials or APK contents are read. A local snapshot
keeps releases reproducible and the private setup form works without fetch().
"""
import argparse
import json
from pathlib import Path

APPS = ('authenticator', 'canvas', 'charge', 'flashcards', 'mail', 'places')
OUTPUT = Path(__file__).resolve().parents[1] / 'setup' / 'descriptors.mjs'


def generate(root):
    descriptors = []
    for app in APPS:
        source = root / app / 'android/app/src/main/assets/wave-setup.json'
        if not source.is_file() or source.resolve() != source or source.stat().st_size > 32768:
            raise ValueError(f'Expected small descriptor file for {app}')
        descriptor = json.loads(source.read_text(encoding='utf-8'))
        if descriptor['app'] != app or descriptor['format'] != 1:
            raise ValueError(f'Descriptor id or version mismatch for {app}')
        descriptors.append(descriptor)
    return ("// Generated by scripts/sync_setup.py from wave_packages; edit the app assets, not this file.\n"
            + 'export const descriptors = ' + json.dumps(descriptors, indent=2, ensure_ascii=True) + ';\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('packages', type=Path)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = generate(args.packages.resolve(strict=True))
    if args.check:
        if not OUTPUT.exists() or text != OUTPUT.read_text(encoding='utf-8'):
            raise SystemExit('Site descriptors differ; review the wave_packages changes and sync again.')
    else:
        OUTPUT.write_text(text, encoding='utf-8')
